taiwanTerms.sort((a, b) => b[0].length - a[0].length);

export function applyTaiwanTerminology(text: string): string {
  return taiwanTerms.reduce(
    (result, [source, target]) => result.split(source).join(target),
    text
  );
}

export function localizeZhTW(
  text: string,
  converter: ChineseConverter | null = null
): string {
  if (!text || !CJK_TEXT.test(text)) return text;

  let converted = text;
  if (converter) {
    try {
      converted = converter(text);
    } catch {
      converted = text;
    }
  }

  return applyTaiwanTerminology(converted);
}

export const zhTW = {
  locale,
  localize: localizeZhTW,
};
